// backend/test/unit/sc-data-load-ops.test.ts
//
// Adding one sample-data CSV to its EXISTING SC_Data table. The load's whole job is
// to be safe on a table that already holds data — it never creates, drops or empties
// anything, and a row whose uid is already there is left out — so most of what is
// tested here is what does NOT happen: rows not doubled, rows not sent blind, a staged
// temp file not left behind, a count not taken on trust.
//
// IRIS is the fake in `helpers/fake-sc-data-iris.ts`, which simulates the behaviour
// measured on the real instance (LOAD DATA reads the staged file, skips a duplicate
// primary key without complaining). The real statement is covered by the live
// integration test.
