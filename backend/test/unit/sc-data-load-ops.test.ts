/**
 * What the route hands the loader per file: the CSV's name (for the report and the error
 * messages) and the table its name resolved to. Nothing else — a header is matched
 * against the installed columns, so there is no per-file configuration to pass.
 */
const CARRIERS = { file: 'carriers.csv', table: 'Carrier' };
const LOCATIONS = { file: 'locations.csv', table: 'Location' };

/**
 * A table description, as INFORMATION_SCHEMA would give it: the listed columns are
 * writable, plus the read-only trio every SC_Data table really has. Every column is a
 * VARCHAR unless `types` says otherwise, which is true of nearly all of SC_Data.
 */
function tableInfo(
  table: string,
  columns: string[],
  readOnly = READ_ONLY,
  types: Record<string, string> = {},
): ScDataTableInfo {
  const map = (names: readonly string[]) => new Map(names.map((c) => [c.toLowerCase(), c]));
  const all = [...columns, ...readOnly];
  return {
    table,
    columns: map(all),
    writable: map(columns),
    types: new Map(all.map((c) => [c.toLowerCase(), (types[c] ?? 'VARCHAR').toUpperCase()])),
  };
}

/** Real columns a load must never write to (identity / generated). */
const READ_ONLY = ['ID', 'lastUpdatedTime', 'recordCreatedTime'];

/** Load one CSV against a fresh fake, returning both the result and the fake. */
async function load(
  csv: string,
  target: { file: string; table: string } = CARRIERS,
  options: FakeScDataOptions = {},
) {
  const iris = createFakeScDataIris(options);
  const result = await loadScDataCsv(iris.deps, { ...target, csv });
  return { result, iris };
}

/**
 * The Error a load rejected with, so a test can examine the WHOLE message instead of
 * matching one pattern at a time — which is what a test about the DIAGNOSIS has to do:
 * what the message now says, and what it no longer says.
 */
async function failedLoad(
  iris: FakeScDataIris,
  target: { file: string; table: string } = CARRIERS,
  csv: string = CARRIER_CSV,
): Promise<Error> {
  return loadScDataCsv(iris.deps, { ...target, csv }).then(
    () => {
      throw new Error('Expected the load to fail.');
    },
    (err: unknown) => err as Error,
  );
}

/** The staged file's lines (it always ends with a newline, which split leaves empty). */
function stagedLines(text: string | undefined): string[] {
  return (text ?? '').replace(/\n$/, '').split('\n');
}

const CARRIER_CSV = 'ID,Name,Type,Status\nCAR-1,Speedy,Road,Active\nCAR-2,Air1,Air,Active\n';

describe('describeScDataTable', () => {
  it('reports the table and its columns AS IRIS SPELLS THEM, matched case-insensitively', async () => {
    // The product spells some columns differently from its own class definition
    // (customerID vs customerId), so the names that go into the statement have to come
    // from IRIS rather than from the file's header or from anything here.
    const iris = createFakeScDataIris({ tables: { SalesShipment: ['uid', 'customerID', 'status'] } });
    const info = await describeScDataTable(iris.deps.sql, 'salesshipment');

    expect(info?.table).toBe('SalesShipment');
    expect(info?.columns.get('customerid')).toBe('customerID');
  });

  it('separates the columns a load may WRITE from the ones it may only read', async () => {
    const iris = createFakeScDataIris();
    const info = await describeScDataTable(iris.deps.sql, 'Carrier');

    // The trio is really there…
    expect([...(info?.columns.keys() ?? [])]).toEqual(
      expect.arrayContaining(['id', 'lastupdatedtime', 'recordcreatedtime']),
    );
    // …and none of it may be written: ID is the identity column, the two timestamps are
    // generated by the product.
    expect([...(info?.writable.keys() ?? [])]).toEqual(['uid', 'name', 'type', 'status']);
  });

  it('is undefined when the namespace has no such table', async () => {
    const iris = createFakeScDataIris({ tables: { Carrier: null } });
    expect(await describeScDataTable(iris.deps.sql, 'Carrier')).toBeUndefined();
  });
});

describe('planScDataColumns', () => {
  const info = tableInfo('Carrier', DEFAULT_TABLES.Carrier as string[]);

  it('pairs each header with the column of that name, ignoring case and surrounding spaces', () => {
    const plans = planScDataColumns('carriers.csv', [' id ', 'NAME', 'type', 'Status'], info);
    expect(plans.map((p) => [p.column, p.index])).toEqual([
      ['uid', 0],
      ['name', 1],
      ['type', 2],
      ['status', 3],
    ]);
  });

  it('pairs by header NAME, so the file\'s column order does not matter', () => {
    // Columns are matched by name and read by the index that name sits at, so a set
    // whose files were exported with the columns in another order still loads. The
    // plan comes back with the key first, whatever the file's order is.
    const plans = planScDataColumns('carriers.csv', ['Status', 'Type', 'Name', 'ID'], info);
    expect(plans.map((p) => [p.column, p.index])).toEqual([
      ['uid', 3],
      ['status', 0],
      ['type', 1],
      ['name', 2],
    ]);
  });

  it('ignores a header no column of the table has, wherever it sits in the file', () => {
    // An extra column in the middle must not shift the ones after it.
    const plans = planScDataColumns(
      'carriers.csv',
      ['ID', 'Comment', 'Name', 'Type', 'Status'],
      info,
    );
    expect(plans.map((p) => [p.column, p.index])).toEqual([
      ['uid', 0],
      ['name', 2],
      ['type', 3],
      ['status', 4],
    ]);
  });

  it('LOADS any column the installed table has, including ones no shipped file carries', () => {
    // SC_Data.Location really has region/latitude/longitude. A set exported out of
    // SC_Data — or a shipped file someone added a column to — must get those values in
    // rather than have them dropped, without anything here being told they exist.
    const rich = tableInfo('Location', [...(DEFAULT_TABLES.Location as string[]), 'region', 'latitude']);
    const plans = planScDataColumns('locations.csv', ['ID', 'Name', 'latitude', 'Region'], rich);

    // The key first, then the leftovers in the file's own order.
    expect(plans.map((p) => [p.column, p.index])).toEqual([
      ['uid', 0],
      ['name', 1],
      ['latitude', 2],
      ['region', 3],
    ]);
    // Spelled as IRIS spells the column, not as the file spelled the header.
    expect(plans.map((p) => p.column)).toContain('region');
  });

  it('NEVER writes the identity ID or a generated timestamp, however the CSV names them', () => {
    // These columns exist, so they cannot be refused on absence: ID is filled by
    // $i(^SC.Data.CarrierD) and recordCreatedTime is read-only after insert.
    const plans = planScDataColumns(
      'carriers.csv',
      ['UID', 'Name', 'ID', 'lastUpdatedTime', 'RecordCreatedTime'],
      info,
    );
    expect(plans.map((p) => p.column)).toEqual(['uid', 'name']);
  });

  it('takes UID for the key wherever it sits, and does not send the key twice', () => {
    // A file with both spellings means two different things by them, and either way round
    // the business key must win — see KEY_HEADERS.
    for (const header of [['ID', 'UID', 'Name'], ['UID', 'ID', 'Name']]) {
      const plans = planScDataColumns('carriers.csv', header, info);
      expect(plans.filter((p) => p.column === 'uid'), header.join()).toHaveLength(1);
      expect(plans.find((p) => p.column === 'uid')?.index, header.join()).toBe(
        header.indexOf('UID'),
      );
    }
  });

  it('leaves out a column the file has no header for, instead of failing the file', () => {
    // demandPlan.csv legitimately has no quantityUom; refusing its 738 rows over one
    // absent optional column would serve nobody.
    const demandInfo = tableInfo('DemandPlan', DEFAULT_TABLES.DemandPlan as string[]);
    const plans = planScDataColumns(
      'demandPlan.csv',
      ['ID', 'productId', 'locationId', 'startDate', 'quantity'],
      demandInfo,
    );
    expect(plans.map((p) => p.column)).toEqual([
      'uid',
      'productId',
      'locationId',
      'startDate',
      'quantity',
    ]);
  });

  it('DROPS a column the installed table does not have, so nothing is sent blind', () => {
    const older = tableInfo('Carrier', ['uid', 'name']);
    const plans = planScDataColumns('carriers.csv', ['ID', 'Name', 'Type', 'Status'], older);
    expect(plans.map((p) => p.column)).toEqual(['uid', 'name']);
  });

  it('reads a repeated header from its FIRST column', () => {
    const plans = planScDataColumns('carriers.csv', ['ID', 'Name', 'name'], info);
    expect(plans.find((p) => p.column === 'name')?.index).toBe(1);
  });

  it('THROWS when the file has no uid header — those rows have no key at all', () => {
    expect(() => planScDataColumns('carriers.csv', ['Name', 'Type'], info)).toThrow(
      /carriers\.csv has no UID or ID column/,
    );
  });

  it('THROWS when the table itself has no uid column', () => {
    const keyless = tableInfo('Carrier', ['name', 'type']);
    expect(() => planScDataColumns('carriers.csv', ['ID', 'Name'], keyless)).toThrow(
      /no UID or ID column/,
    );
  });
});

describe('unmatchedHeaders', () => {
  const info = tableInfo('Carrier', DEFAULT_TABLES.Carrier as string[]);
  const left = (header: string[]) =>
    unmatchedHeaders(header, planScDataColumns('carriers.csv', header, info));

  it('names the columns whose values did not load, and nothing else', () => {
    // The table has no `Comment` column, so those values went nowhere. Reporting it is
    // the whole point: a header that lands nowhere is invisible otherwise, and with every
    // column resolved by name a respelled header is exactly what that looks like.
    expect(left(['ID', 'Comment', 'Name', 'Type', 'Status'])).toEqual(['Comment']);
  });

  it('is empty when every header found a column', () => {
    expect(left(['ID', 'Name', 'Type', 'Status'])).toEqual([]);
  });

  it('reports a header the file spells wrong, which is what a renamed column looks like', () => {
    expect(left(['ID', 'Nmae', 'Type', 'Status'])).toEqual(['Nmae']);
  });

  it('reports the columns a load must never write to — they did not load either', () => {
    // `ID` here is the identity column, not the key: the key pass took `UID`. Saying so is
    // honest — those values were not stored.
    expect(left(['UID', 'Name', 'ID', 'recordCreatedTime'])).toEqual(['ID', 'recordCreatedTime']);
  });

  it('keeps the file\'s own spelling and order, once each, ignoring blanks', () => {
    expect(left(['ID', ' Extra ', 'Name', 'EXTRA', '', '   ', 'Other'])).toEqual([
      'Extra',
      'Other',
    ]);
  });

  it('does not report the key header, whichever spelling loaded it', () => {
    // `ID` fed `uid`, so it is not "left over" — reporting it would send whoever reads the
    // report looking for a column that did load.
    expect(left(['ID', 'Name'])).toEqual([]);
    expect(left(['UID', 'Name'])).toEqual([]);
  });
});

describe('the staged CSV', () => {
  it('quotes a cell only when it must, and doubles an embedded quote', () => {
    expect(csvCell('Speedy')).toBe('Speedy');
    expect(csvCell('')).toBe('');
    expect(csvCell('34.75, 113.68')).toBe('"34.75, 113.68"');
    expect(csvCell('say "hi"')).toBe('"say ""hi"""');
    expect(csvCell('two\nlines')).toBe('"two\nlines"');
    expect(csvRow(['a', 'b,c', ''])).toBe('a,"b,c",');
  });

  it('leads with the TARGET column names and ends with a newline', () => {
    // The header is rewritten to the target columns precisely so no header spelling,
    // space or case can reach the SQL statement.
    const text = buildStagedCsv(['uid', 'name'], [['CAR-1', 'Speedy']]);
    expect(text).toBe('uid,name\nCAR-1,Speedy\n');
    expect(buildStagedCsv(['uid'], [])).toBe('uid\n');
  });
});

